#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""P3 case generator for T10.a1-frame-top (offline, test-only).

Creates deterministic packed-RAW10 frames, one generated wrapper module per
case (geometry is a compile-time parameter of a1_frame_top), and index.json.
No board, no production path.
"""
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from a1_ref import pack_samples  # noqa: E402


def raw_frame(kind, w, h):
    stride = w * 5 // 4
    seed = (0x1234_5678 ^ (w << 8) ^ h) & 0xFFFFFFFF
    if w % 4 != 0:
        # illegal-geometry probe: packing is undefined, only the first beat
        # is ever consumed; emit deterministic bytes of the TB's length.
        out = bytearray()
        for _ in range(stride * h):
            seed = (seed * 1103515245 + 12345) & 0xFFFFFFFF
            out.append((seed >> 16) & 0xFF)
        return bytes(out)
    out = bytearray()
    for y in range(h):
        vals = []
        for x in range(w):
            if kind == "grad":
                s = (x * 3 + y * 5 + ((x * y) >> 6)) & 0x3FF
            elif kind == "odd":
                s = (x * 17 + y * 29 + (((x // 4) + y) % 3) * 64) & 0x3FF
            elif kind == "bypass":
                s = (x * 37 + y * 101 + x * y * 13) & 0x3FF
            elif kind == "rand":
                seed = (seed * 1103515245 + 12345) & 0xFFFFFFFF
                s = (seed >> 11) & 0x3FF
            elif kind == "mixed":
                if y < (h // 2):
                    s = (x * 3 + y * 5 + ((x * y) >> 6)) & 0x3FF
                else:
                    seed = (seed * 1103515245 + 12345) & 0xFFFFFFFF
                    s = (seed >> 11) & 0x3FF
            else:
                raise ValueError(kind)
            vals.append(s)
        blk = pack_samples(vals)
        if len(blk) != stride:
            raise AssertionError("stride mismatch")
        out += blk
    return bytes(out)


CASES = [
    # name, W, H, kind, prep, pred, mode, extra
    ("f1080p_p1d1",   1920, 1080, "grad",   1, 1, 0, {}),
    ("f1080p_p1d0",   1920, 1080, "grad",   1, 0, 0, {}),
    ("f1080p_p0",     1920, 1080, "grad",   0, 0, 0, {}),
    ("f1080p_rand",   1920, 1080, "rand",   1, 1, 0, {}),
    ("odd20x5_p1d1",    20,    5, "odd",    1, 1, 0, {}),
    ("odd20x5_p1d0",    20,    5, "odd",    1, 0, 0, {}),
    ("bypass12x6",      12,    6, "bypass", 0, 0, 0, {}),
    ("rand1920x16",   1920,   16, "rand",   1, 1, 0, {}),
    ("mixed1920x16",  1920,   16, "mixed",  1, 1, 0, {}),
    ("multi1080p",    1920, 1080, "grad",   1, 1, 6, {"nframes": 2}),
    ("abort_recover",   20,    5, "odd",    1, 1, 1, {"abort_at": 12}),
    ("reset_recover",   20,    5, "odd",    1, 1, 2, {"rst_at": 12}),
    ("proto_recover",   20,    5, "odd",    1, 1, 3, {"proto_at": 12}),
    ("bp20x5",          20,    5, "odd",    1, 1, 5, {}),
    ("stall_abort",   1920,   16, "grad",   1, 1, 4, {"abort_at": 3000}),
    ("abort_last",      20,    5, "odd",    1, 1, 7, {}),
    ("neg_wmod4",       18,    4, "odd",    1, 1, 8, {}),
    ("neg_h1",          20,    1, "odd",    1, 1, 8, {}),
    ("neg_oversize",  1924,    4, "odd",    1, 1, 8, {}),
    ("neg_pred0prep0",  20,    5, "odd",    0, 1, 9, {}),
]


def main(argv):
    root = Path(argv[1]).resolve() if len(argv) > 1 else HERE.parents[4]
    out = Path(argv[2]).resolve() if len(argv) > 2 else (
        root / "workflow/runs/20261020-0209_singleA_aplus_closedloop/T10.a1-frame-top/p3")
    cases_dir = out / "cases"
    cases_dir.mkdir(parents=True, exist_ok=True)
    (out / "runs").mkdir(parents=True, exist_ok=True)
    (out / "logs").mkdir(parents=True, exist_ok=True)

    wrappers = ["// generated by a1_p3_gen.py -- one wrapper per geometry",
                "`timescale 1ns / 1ps", ""]
    index = {"generator": "tools/codec/a1_p3_gen.py", "cases": []}
    cache = {}

    for (name, w, h, kind, prep, pred, mode, extra) in CASES:
        key = (kind, w, h)
        if key not in cache:
            cache[key] = raw_frame(kind, w, h)
        raw = cache[key]
        d = cases_dir / name
        d.mkdir(exist_ok=True)
        (d / "raw.bin").write_bytes(raw)
        ent = {
            "name": name, "w": w, "h": h, "kind": kind,
            "prep": prep, "pred": pred, "mode": mode,
            "raw": str((d / "raw.bin").relative_to(out)).replace("\\", "/"),
            "raw_sha256": __import__("hashlib").sha256(raw).hexdigest(),
            "raw_len": len(raw),
        }
        ent.update(extra)
        if mode in (1, 2, 3, 4, 7, 9):
            kind2 = "bypass" if kind == "odd" else "odd"
            key2 = (kind2, w, h)
            if key2 not in cache:
                cache[key2] = raw_frame(kind2, w, h)
            raw2 = cache[key2]
            (d / "raw2.bin").write_bytes(raw2)
            ent["raw2"] = str((d / "raw2.bin").relative_to(out)).replace("\\", "/")
            ent["raw2_sha256"] = __import__("hashlib").sha256(raw2).hexdigest()
            ent["raw2_len"] = len(raw2)
            ent["prep2"] = prep
            ent["pred2"] = pred
            if mode == 9:
                ent["prep2"] = 1
                ent["pred2"] = 0
        index["cases"].append(ent)
        wrappers.append("module tb_c_%s; tb_a1_frame_top #(.W(%d), .H(%d)) u(); endmodule\n"
                        % (name, w, h))

    (cases_dir / "case_wrappers.v").write_text("\n".join(wrappers), encoding="ascii")
    (cases_dir / "index.json").write_text(json.dumps(index, indent=2), encoding="utf-8")
    print("cases=%d out=%s" % (len(index["cases"]), out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
