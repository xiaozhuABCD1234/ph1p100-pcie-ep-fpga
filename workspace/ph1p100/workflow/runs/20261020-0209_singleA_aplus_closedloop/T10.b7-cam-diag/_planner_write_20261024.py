def read_any(path):
    raw = open(path, 'rb').read()
    for enc in ('utf-8-sig', 'utf-8', 'gbk'):
        try:
            return raw.decode(enc), enc
        except UnicodeDecodeError:
            pass
    return raw.decode('gbk', errors='replace'), 'gbk'


def prepend(path, block, marker):
    txt, enc = read_any(path)
    if marker in txt:
        print('skip (already has marker):', os.path.basename(path))
        return
    body = txt.lstrip('\ufeff')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(block.rstrip() + '\n\n---\n\n' + body)
    print('prepended:', os.path.basename(path), '(was %s)' % enc)


def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text.rstrip() + '\n')
    print('wrote:', path, len(text), 'chars')


